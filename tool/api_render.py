#!/usr/bin/env python3
"""Renders a dart-apitool extract as one public symbol per line.

    tool/api_render.py <raw extract.json> <out.api.txt>

The output is the committed baseline, api/admoai.api.txt: one symbol per line with its
signature, sorted so a type and its members stay together, readable in a PR diff without
knowing Dart. Only the API is rendered: not the package version (a release bump is not an
API change), not the dependency constraints (Dependabot moves them weekly and cannot
regenerate this file), not source-file locations (moving a declaration is not a change).
"""
import json
import sys

raw_path, txt_out = sys.argv[1:3]
api = json.load(open(raw_path))["packageApi"]


def flags(d):
    out = [f for f, k in (("deprecated", "isDeprecated"), ("experimental", "isExperimental"), ("sealed", "isSealed")) if d.get(k)]
    return f" [{', '.join(out)}]" if out else ""


def generics(d):
    names = d.get("typeParameterNames") or []
    return f"<{', '.join(names)}>" if names else ""


def params(ps):
    positional, optional, named = [], [], []
    for p in ps:
        text = f"{p['typeName']} {p['name']}"
        if p.get("isNamed"):
            named.append(("required " if p.get("isRequired") else "") + text)
        elif p.get("isRequired"):
            positional.append(text)
        else:
            optional.append(text)
    parts = positional[:]
    if optional:
        parts.append("[" + ", ".join(optional) + "]")
    if named:
        parts.append("{" + ", ".join(named) + "}")
    return "(" + ", ".join(parts) + ")"


# Each line starts with the symbol's name (Owner or Owner.member), so sorting keeps a type
# and its members together.
def executable(owner, e):
    static = "static " if e.get("isStatic") else ""
    if e["type"] == "constructor":
        name = e["name"] or "new"
        return f"{owner}.{name}  constructor{params(e['parameters'])}{flags(e)}"
    name = f"{owner}.{e['name']}" if owner else e["name"]
    return f"{name}  {static}method{generics(e)}{params(e['parameters'])} -> {e['returnTypeName']}{flags(e)}"


def field(owner, f):
    static = "static " if f.get("isStatic") else ""
    access = "read" + ("/write" if f.get("isWriteable") else "") if f.get("isReadable", True) else "write"
    name = f"{owner}.{f['name']}" if owner else f["name"]
    return f"{name}  {static}field: {f['typeName']} ({access}){flags(f)}"


lines = []
for i in api["interfaceDeclarations"]:
    supers = [s for s in i.get("superTypeNames", []) if s != "Object"]
    lines.append(f"{i['name']}  type{generics(i)}" + (f" : {', '.join(sorted(supers))}" if supers else "") + flags(i))
    for e in i.get("executableDeclarations", []):
        lines.append(executable(i["name"], e))
    for f in i.get("fieldDeclarations", []):
        lines.append(field(i["name"], f))
for e in api["executableDeclarations"]:
    lines.append(executable("", e))
for f in api["fieldDeclarations"]:
    lines.append(field("", f))
for t in api["typeAliasDeclarations"]:
    lines.append(f"{t['name']}  typedef = {t['aliasedTypeName']}{flags(t)}")

header = [
    "# Public API of the admoai package — GENERATED by tool/api.sh, do not edit.",
    "# One symbol per line. A removed or changed line is a breaking change (see README,",
    "# \"When the API check fails\").",
]
open(txt_out, "w").write("\n".join(header + sorted(set(lines))) + "\n")
